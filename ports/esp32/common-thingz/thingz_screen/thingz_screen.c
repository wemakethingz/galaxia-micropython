void thingz_screen_print_screen_with_glyp_index(uint8_t* str, uint32_t len, uint32_t x, uint32_t y, uint16_t foreground){
    uint8_t cpt = 0;
    while(cpt <  len){
        
        uint8_t* glyph = font_get_glyph_from_index(str[cpt]);
        /*
            _________
              |000100
              |001100
              |010100
            ^ |000100
            | |001110
            |________
            scan direction ->
        */
        for(int k = 0; k < thingz_screen.params.font_width; k++){
            for(int l = 0; l < thingz_screen.params.font_height; l++){
                thingz_screen.lineData[thingz_screen.params.font_width*thingz_screen.params.font_height*cpt+k*thingz_screen.params.font_height+l] = glyph[k*thingz_screen.params.font_height+l] == 1 ? foreground : 0; 
            }
        }

        cpt++;

    }

    spi_master_write_comm_byte(&(thingz_screen.dev), 0x2A);	// set column(x) address
    spi_master_write_data_word(&(thingz_screen.dev), thingz_screen.params.offsetx+y);
    spi_master_write_data_word(&(thingz_screen.dev), y+(thingz_screen.params.font_height+thingz_screen.params.offsetx-1));
    spi_master_write_comm_byte(&(thingz_screen.dev), 0x2B);	// set Page(y) address
    spi_master_write_data_word(&(thingz_screen.dev), thingz_screen.params.offsety+x);
    spi_master_write_data_word(&(thingz_screen.dev), thingz_screen.params.font_width*cpt+thingz_screen.params.offsety+x-1);

    spi_master_write_comm_byte(&(thingz_screen.dev), 0x2C);	// Memory Write
    uint32_t end = thingz_screen.params.font_width*thingz_screen.params.font_height*cpt;
    for(int j = 0; j < end; j+=500){
        uint16_t s = end-j > 500 ? 500 : end-j;
        spi_master_write_colors(&(thingz_screen.dev), thingz_screen.lineData+j, s);
    }
}

void thingz_screen_print_screen(uint8_t* str, uint32_t len, uint32_t x, uint32_t y, uint16_t foreground, uint8_t utf8){
    uint8_t* i = str;
    uint8_t cpt = 0;
    while(i < str + len){
        
        uint8_t c = *i;
        if(utf8){
            c = utf8_get_char(i);
            i = utf8_next_char(i);
        }else{
            i++;
        }
        uint8_t* glyph = font_get_glyph(c);
        /*
            _________
              |000100
              |001100
              |010100
            ^ |000100
            | |001110
            |________
            scan direction ->
        */
        for(int k = 0; k < thingz_screen.params.font_width; k++){
            for(int l = 0; l < thingz_screen.params.font_height; l++){
				uint16_t index = thingz_screen.params.font_width*thingz_screen.params.font_height*cpt+k*thingz_screen.params.font_height+l;
				if( index < thingz_screen.lineDataSize)
                	thingz_screen.lineData[index] = glyph[k*thingz_screen.params.font_height+l] == 1 ? foreground : 0; 
            }
        }

        cpt++;

    }

    spi_master_write_comm_byte(&(thingz_screen.dev), 0x2A);	// set column(x) address
    spi_master_write_data_word(&(thingz_screen.dev), thingz_screen.params.offsetx+y);
    spi_master_write_data_word(&(thingz_screen.dev), y+(thingz_screen.params.font_height+thingz_screen.params.offsetx-1));
    spi_master_write_comm_byte(&(thingz_screen.dev), 0x2B);	// set Page(y) address
    spi_master_write_data_word(&(thingz_screen.dev), thingz_screen.params.offsety+x);
    spi_master_write_data_word(&(thingz_screen.dev), thingz_screen.params.font_width*cpt+thingz_screen.params.offsety+x-1);

    spi_master_write_comm_byte(&(thingz_screen.dev), 0x2C);	// Memory Write
    uint32_t end = thingz_screen.params.font_width*thingz_screen.params.font_height*cpt;
	if(end > thingz_screen.lineDataSize){
		end = thingz_screen.lineDataSize;
	}
    for(int j = 0; j < end; j+=500){
        uint16_t s = end-j > 500 ? 500 : end-j;
        spi_master_write_colors(&(thingz_screen.dev), thingz_screen.lineData+j, s);
    }

}

void thingz_screen_switch_mode(uint8_t mode){
    uint8_t oldMode = thingz_screen.current_mode;
    xSemaphoreTake(controlLcd, portMAX_DELAY);
    thingz_screen.current_mode = mode;
    xSemaphoreGive(controlLcd);
    switch(oldMode){
        case COMMON_THINGZ_SCREEN_MODE_REPL:
            thingz_screen_repl_exit();
        break;
        case COMMON_THINGZ_SCREEN_MODE_DEBUG:

        break;
        case COMMON_THINGZ_SCREEN_MODE_PLOT:
            thingz_screen_plot_exit(&thingz_screen.plot);
        break;
		case COMMON_THINGZ_SCREEN_MODE_RAW:
			thingz_screen_raw_exit(&thingz_screen.raw);
		break;
    }
    thingz_screen_clear();
    switch(mode){
        case COMMON_THINGZ_SCREEN_MODE_REPL:
            thingz_screen_repl_enter();
        break;
        case COMMON_THINGZ_SCREEN_MODE_DEBUG:

        break;
        case COMMON_THINGZ_SCREEN_MODE_PLOT:
            thingz_screen_plot_enter(&thingz_screen.plot);
        break;
		case COMMON_THINGZ_SCREEN_MODE_RAW:
			thingz_screen_raw_enter(&thingz_screen.raw);
		break;
    }
    
}

uint8_t thingz_screen_get_mode(){
    return thingz_screen.current_mode;
}

void thingz_screen_print_header(const char* filename){
    xSemaphoreTake(controlLcd, portMAX_DELAY);
    lcdDrawFillRect(&thingz_screen.dev, MICROPY_THINGZ_SCREEN_HEIGHT-15, 0, MICROPY_THINGZ_SCREEN_HEIGHT-1, MICROPY_THINGZ_SCREEN_WIDTH-1, 0);
    uint16_t color = 0x07e0;
    char* exception = debug_mode_get_last_exception();
    if(exception && strlen(exception) > 0){
        color = 0xf800;
        thingz_screen_print_screen((uint8_t*)"Erreur", strlen("Erreur"), 0, MICROPY_THINGZ_SCREEN_HEIGHT-14, 0xFFFF, 1);
    }else{
        if(!pyexec_repl_active){
            thingz_screen_print_screen(filename, strlen(filename), 0, MICROPY_THINGZ_SCREEN_HEIGHT-14, 0xFFFF, 1);

        }else{
            thingz_screen_print_screen((uint8_t*)"REPL", strlen("REPL"), 0, MICROPY_THINGZ_SCREEN_HEIGHT-14, 0xFFFF, 1);
        }
    }
    
    lcdDrawLine(&thingz_screen.dev,  MICROPY_THINGZ_SCREEN_HEIGHT-16, 0, MICROPY_THINGZ_SCREEN_HEIGHT-16, MICROPY_THINGZ_SCREEN_WIDTH-1, 0xFFFF);
    lcdDrawFillCircle(&thingz_screen.dev, (MICROPY_THINGZ_SCREEN_HEIGHT-16)+7, MICROPY_THINGZ_SCREEN_WIDTH-10, 4, color);
    xSemaphoreGive(controlLcd);
}

void thingz_screen_clear(){
    xSemaphoreTake(controlLcd, portMAX_DELAY);
    lcdFillScreen(&thingz_screen.dev, BLACK);
    xSemaphoreGive(controlLcd);
}

void thingz_screen_lock(){
	xSemaphoreTake(controlLcd, portMAX_DELAY);
}

void thingz_screen_unlock(){
	xSemaphoreGive(controlLcd);
}

void thingz_screen_autorefresh(uint8_t autorefresh){
	if(thingz_screen.autorefresh == 0 && autorefresh){
		_thingz_screen_refresh(NULL);
		esp_timer_start_periodic(refreshTimer, 40*1000);
		thingz_screen.autorefresh = 1;
	}else{
		esp_timer_stop(refreshTimer);
		thingz_screen.autorefresh = 0;
	}
}

